"""Build the IEEE manuscript's two plots and table from audited effects.json."""
import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[2]
LABELS = {
    "S0": "S0 Static", "S1": "S1 Base LM", "S2": "S2 Base LM + critique",
    "S3": "S3 Direct LoRA", "S4": "S4 Agentic at 5 s", "S5": r"\textbf{S5 SELF-X}",
    "threshold": "Capacity threshold", "least_loaded": "Least loaded",
    "tabular_q": "Tabular Q", "dqn": "DQN", "marl": "Two-agent IQL",
    "dpp": "DPP only", "no_lora": "S5 without LoRA", "no_governor": "S5 without governor",
}
PALETTE = {"blue": "#1b5f96", "green": "#00785f", "slate": "#475569"}


def build(source, output):
    data = json.loads(source.read_text(encoding="utf-8"))
    comps = data["comparisons"]
    output.mkdir(parents=True, exist_ok=True)
    rows = []
    for key, label in LABELS.items():
        m = data["agentic"] if key == "S5" else comps[key]
        rows.append(f"{label} & {m['latency_ms']:.2f} & {m['loss_pct']:.2f} & "
                    f"{m['goodput_mbps']:.3f} " + r"\\")
    (output / "manuscript_table.tex").write_text(
        "% Generated by plot_manuscript.py\n\\newcommand{\\AuditManuscriptRows}{%\n"
        + "\n".join(rows) + "\n}\n", encoding="utf-8"
    )

    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 8.2,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "axes.axisbelow": True, "pdf.fonttype": 42})
    fig, axes = plt.subplots(2, 1, figsize=(3.52, 2.95),
                             gridspec_kw={"height_ratios": (2, 4)})
    for ax, keys, xlim, title in (
        (axes[0], ["S0", "S4"], (-30, 2), "Static and matched slow controller"),
        (axes[1], ["dqn", "dpp", "no_lora", "no_governor"], (-1.08, 0.74),
         "Fast controllers and ablations"),
    ):
        ax.axvline(0, linewidth=0.8, color="#64748b", linestyle="--")
        for i, key in enumerate(keys):
            effect = comps[key]["changes"]["latency_ms"]
            x = effect["delta"]
            a, b = effect["ci95"]
            ax.errorbar(x, i, xerr=[[x-a], [b-x]], fmt="o", markersize=3.5,
                        color=PALETTE["blue"], linewidth=1.1, capsize=2)
        names = [LABELS[key] if key != "dqn" else "DQN / IQL" for key in keys]
        ax.set(yticks=range(len(keys)), yticklabels=names, xlim=xlim,
               ylim=(len(keys)-0.5, -0.5))
        ax.set_title(title, loc="left", fontsize=8.2)
        ax.grid(axis="x", color="#e2e8f0", linewidth=.65)
        ax.tick_params(axis="y", length=0, pad=3)
    axes[-1].set_xlabel("Paired mean delay difference (ms)")
    fig.tight_layout(pad=.35, h_pad=.9)
    fig.savefig(output / "paper_delay_effects.pdf", metadata={"CreationDate": None})
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(3.52, 2.50))
    points = (
        ("S0", "S0 Static", (-5, -4), "right"),
        ("S4", "S4 Agentic at 5 s", (5, 3), "left"),
        ("S5", "S5 SELF-X", (5, 8), "left"),
        ("dqn", "DQN / IQL", (4, 8), "left"),
        ("no_lora", "S5 without LoRA", (3, -13), "left"),
    )
    for key, label, offset, alignment in points:
        m = data["agentic"] if key == "S5" else comps[key]
        x, y = m["loss_pct"], m["latency_ms"]
        color = PALETTE["green"] if key == "S5" else PALETTE["slate"]
        ax.scatter(x, y, s=19, color=color, marker="D" if key == "S5" else "o")
        ax.annotate(label, (x, y), xytext=offset, textcoords="offset points",
                    arrowprops=dict(arrowstyle="-", linewidth=.55, color=color,
                                    shrinkA=1, shrinkB=3) if key in ("dqn", "no_lora") else None,
                    color=color, ha=alignment, fontsize=7.7)
    ax.set(xlabel="Lost offered volume (%)", ylabel="Mean delay (ms)",
           xlim=(24.37, 26.16), ylim=(57, 84))
    ax.grid(color="#e2e8f0", linewidth=.65)
    fig.tight_layout(pad=.35)
    fig.savefig(output / "paper_delay_loss.pdf", metadata={"CreationDate": None})
    plt.close(fig)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--effects", type=Path, default=ROOT / "paper/comparison/effects.json")
    parser.add_argument("--output", type=Path, default=ROOT / "paper/comparison")
    args = parser.parse_args()
    build(args.effects, args.output)
